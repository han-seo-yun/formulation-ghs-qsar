def runs(p, text, size=12):
    """해석하는 표기는 `` `코드` `` 하나뿐이다.

    회의자료 판은 `**굵게**` 와 색을 함께 해석하는데 이 형식은 강조를 쓰지 않는다.
    `**` 를 지운 것이 아니라 아예 안 받으므로, 원고에 남아 있으면 그대로 찍혀
    눈에 띈다 — 조용히 사라지지 않게 일부러 이렇게 둔다.
    """
    import re

    for tok in re.split(r"(`[^`]+`|\n)", text):
        if not tok:
            continue
        if tok == "\n":
            p.add_run().add_break()
            continue
        assert "**" not in tok, f"이 형식은 굵게를 쓰지 않는다: {tok}"
        is_code = tok.startswith("`")
        r = p.add_run(tok[1:-1] if is_code else tok)
        r.font.name = MONO if is_code else KO
        r.font.size = Pt(size - 1.5 if is_code else size)
        r._element.rPr.rFonts.set(qn("w:eastAsia"), KO)
    return p


